#!/usr/bin/env python3
"""Build OFFGRID 180.

- Writes web/js/version.js with the build version.
- Generates web/sw.js that precaches every app file (so the PWA works fully offline).
- Optionally copies the web app into the Android project's assets.

Usage: python3 offgrid180/build.py [VERSION] [--android]
"""
import hashlib, json, os, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.join(HERE, 'web')
version = next((a for a in sys.argv[1:] if not a.startswith('--')), 'dev')

with open(os.path.join(WEB, 'js', 'version.js'), 'w') as f:
    f.write("window.OG_BUILD = %s;\n" % json.dumps(version))

files, h = [], hashlib.sha256()
for root, _, names in os.walk(WEB):
    for n in sorted(names):
        p = os.path.join(root, n)
        rel = os.path.relpath(p, WEB).replace(os.sep, '/')
        if rel == 'sw.js':
            continue
        files.append(rel)
        h.update(rel.encode()); h.update(open(p, 'rb').read())
files.sort()
cache = 'offgrid180-' + version + '-' + h.hexdigest()[:10]

SW = """/* OFFGRID 180 service worker (generated by build.py). Cache-first: the whole app works offline. */
const CACHE = %s;
const FILES = %s;
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(['./'].concat(FILES))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('offgrid180-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return; // optional online features (forecast) go straight to network
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); }
    return res;
  }).catch(() => caches.match('./index.html'))));
});
""" % (json.dumps(cache), json.dumps(files, indent=0))
with open(os.path.join(WEB, 'sw.js'), 'w') as f:
    f.write(SW)
print('sw.js:', cache, len(files), 'files')

if '--android' in sys.argv:
    dest = os.path.join(HERE, 'android', 'app', 'src', 'main', 'assets', 'www')
    shutil.rmtree(dest, ignore_errors=True)
    shutil.copytree(WEB, dest)
    print('copied web app ->', dest)
